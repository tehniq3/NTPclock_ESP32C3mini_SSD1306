const int NUM_HISTORY_EVENTS =
  sizeof(HISTORY_EVENTS) / sizeof(HISTORY_EVENTS[0]);

// Returns the next event to display.
//   - If one or more entries match today's date, rotates through them on
//     successive calls (counter resets when date changes).
//   - Otherwise (shouldn't happen now that all 366 days are covered, but
//     kept as a safety net), rotates through the entire table.
inline const HistEvent* getNextCardEvent(int month, int day) {
  static int lastMonth  = 0;
  static int lastDay    = 0;
  static int todayIdx   = 0;
  static int anyIdx     = 0;

  if (month != lastMonth || day != lastDay) {
    lastMonth = month; lastDay = day;
    todayIdx = 0;
  }

  const int MAX = 6;
  const HistEvent* matches[MAX];
  int n = 0;
  for (int i = 0; i < NUM_HISTORY_EVENTS && n < MAX; i++) {
    if (HISTORY_EVENTS[i].month == month && HISTORY_EVENTS[i].day == day) {
      matches[n++] = &HISTORY_EVENTS[i];
    }
  }

  if (n > 0) {
    const HistEvent* e = matches[todayIdx % n];
    todayIdx++;
    return e;
  }

  const HistEvent* e = &HISTORY_EVENTS[anyIdx % NUM_HISTORY_EVENTS];
  anyIdx++;
  return e;
}